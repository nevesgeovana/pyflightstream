"""A matrix row whose geometry is generated (PFS-2214, lane G10 of 0.57.0).

Pipeline role: the workspace row, called by the matrix binding beside
:func:`pyflightstream.workspace._geometry_record.judge_the_row_geometry`. A row whose
``GEOMETRY`` cell names ``<name>.geom.toml`` (or an ``.igs`` with a ``MESH_ROUTE``) is
generated by the SAME :func:`pyflightstream.workspace._geom_run.run_geometry` that the
``pyfs-geom`` verbs and the API call, so a row and the API give one identity for one set of
parameters. The result lives in one folder of ``inputs/geometries/``, named by the identity and
written by atomic rename, so equal parameters reuse it and two rows cannot collide; the row then
opens the ``.fsm`` that the existing geometry stage builds from the instruction written there.

The route of the row (``MESH_ROUTE``) chooses what the instruction is: ``native`` hands the
generated IGES to the solver's CAD importer (``[cad]``), ``quad_dominant`` meshes it with
strategy 1 of PFS-2214 and hands that mesh over (``[mesh]``), and ``full_grid`` meshes it with
strategy 2 (:func:`mesh_with_strategy_2`) and hands that mesh over the same way.

An entry that does not apply to a row is warned and skipped, never refused (her rule of
2026-10-27); what is refused is an input the row cannot be built from: an unknown route, a file
with several configurations and none named, a parameter the file does not hold.
"""

