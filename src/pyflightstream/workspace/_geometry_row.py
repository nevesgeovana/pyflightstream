#: The suffix of a configuration file a row generates from.
GEOMETRY_ROW_SUFFIX = ".geom.toml"

#: The statuses of a generation that a later row may reuse.
_REUSABLE = ("accepted", "incomplete")

#: The last stage each route needs: the native route stops where the IGES is checked, a mesh
#: route stops before the export it replaces with its own mesh.
_UNTIL = {"native": "S12.C", "quad_dominant": "S11", "full_grid": "S11"}

_IGES_SUFFIXES = (".igs", ".iges")

#: The one boundary the solver's CAD importer gives the body it converts, whatever the members of
#: the IGES are (record ``tests/tier3_licensed/data/g13-native-import.json``, build 26.127: a one
#: member file and a two member file both save one boundary named ``Model 0``).
NATIVE_BOUNDARY = "Model 0"


class GeometryRowError(InputArtifactError):
    """A row's geometry could not be produced; the other rows of the matrix are unaffected.

    Attributes
    ----------
    report_path : Path or None
        The ``report.json`` of the generation that failed, when one ran.
    """

    report_path: Path | None = None


@dataclass(frozen=True)
class GeometryRowRequest:
    """What one matrix row asks of the generator, read from its cells.

    Attributes
    ----------
    pol : str
        The row's POL.
    source : Path
        The configuration file, or the IGES file, the row names.
    kind : str
        ``configuration`` for a ``.geom.toml``; ``iges`` for an IGES with a route.
    route : str
        One of :data:`pyflightstream.cases._matrix_layouts.MESH_ROUTES`.
    configuration, variant : str or None, str
        The registry entry and variant of the configuration.
    overrides : dict
        ``{"main.planform.span": 12.0}`` as the API takes them.
    controls : Path or None
        The mesh controls file of a mesh route.
    fs_build : str or None
        The row's own FS_BUILD, which the instruction carries.
    """

    pol: str
    source: Path
    kind: str
    route: str
    configuration: str | None = None
    variant: str = "clean"
    overrides: Mapping[str, Any] | None = None
    controls: Path | None = None
    fs_build: str | None = None


@dataclass(frozen=True)
class RowGeometry:
    """The generated geometry of one row.

    Attributes
    ----------
    folder : Path
        The geometry folder holding the instruction, the IGES and the report.
    name : str
        The instruction's name, which is the folder's.
    geometry : Path
        The ``.fsm`` the instruction builds and the row opens; it exists once the geometry
        stage has built it.
    report : dict
        The generation report, with ``status``, ``parameter_id`` and ``surface_id``.
    reused : bool
        Whether the folder of an earlier equal generation was used.
    """

    folder: Path
    name: str
    geometry: Path
    report: dict[str, Any]
    reused: bool


def _stated(variables: Mapping[str, str], key: str) -> str:
    text = str(variables.get(key, "")).strip()
    return "" if text in UNSTATED_CELLS else text


def _skip(pol: str, key: str, reason: str) -> None:
    """Warn that one stated entry does not apply to the row and is skipped."""
    demote(
        InputValueError(f"matrix row POL {pol}: {key} is skipped; {reason}"),
        warning=NotApplicableWarning,
    )


def _parse_params(text: str, pol: str) -> dict[str, Any]:
    """Read the brace form ``{a.b=1, c.d=true}`` into the override mapping of the API."""
    body = text.strip()
    if not (body.startswith("{") and body.endswith("}")):
        raise GeometryRowError(
            f"matrix row POL {pol}: {GEOM_PARAMS_VARIABLE} is {text!r}; write the overrides in "
            "braces as {main.planform.span=12, main.planform.taper=0.6}."
        )
    overrides: dict[str, Any] = {}
    for pair in (part for part in body[1:-1].split(",") if part.strip()):
        name, equals, value = pair.partition("=")
        if not equals or not name.strip():
            raise GeometryRowError(
                f"matrix row POL {pol}: {GEOM_PARAMS_VARIABLE} entry {pair.strip()!r} is not "
                "name=value."
            )
        overrides[name.strip()] = _typed(value.strip())
    return overrides


def _typed(value: str) -> Any:
    """Read one value as TOML reads it (number, boolean, quoted text), else as the text."""
    try:
        return tomllib.loads(f"v = {value}")["v"]
    except tomllib.TOMLDecodeError:
        return value


def _route_of(variables: Mapping[str, str], pol: str, *, default: str | None) -> str:
    stated = _stated(variables, MESH_ROUTE_VARIABLE)
    if not stated:
        if default is None:
            raise GeometryRowError(f"matrix row POL {pol}: no route to a mesh is stated.")
        return default
    if stated not in MESH_ROUTES:
        raise GeometryRowError(
            f"matrix row POL {pol}: {MESH_ROUTE_VARIABLE} {stated!r} is not a route; the "
            f"routes are {', '.join(MESH_ROUTES)}, or NA for a row whose mesh is a file."
        )
    return stated


def _skip_keys_of_a_mesh_file(variables: Mapping[str, str], pol: str, name: str) -> None:
    """Warn and skip every generation entry of a row that opens a file as it is."""
    for key in (
        MESH_ROUTE_VARIABLE,
        GEOM_CONFIGURATION_VARIABLE,
        GEOM_VARIANT_VARIABLE,
        GEOM_PARAMS_VARIABLE,
        MESH_CONTROLS_VARIABLE,
    ):
        if _stated(variables, key):
            _skip(pol, key, f"the row opens {name} as it is and generates nothing")


def plan_row_geometry(
    variables: Mapping[str, str],
    pol: str,
    resolve: Callable[[str], Path],
    *,
    fs_build: str | None = None,
) -> GeometryRowRequest | None:
    """Read the geometry cells of one row; None when the row generates nothing.

    A ``.geom.toml`` row generates, and states its route or is read as ``native`` with a
    warning. An IGES row with a route generates from that file; without a route it is the
    existing refusal's, untouched. A row opening an FSM, an OBJ or an STL skips every entry
    that would generate, with a warning.

    Parameters
    ----------
    variables : mapping
        The row's variables (the columns folded in, and the free cell).
    pol : str
        The row's POL, for the sentences.
    resolve : callable
        ``workspace.resolve_geometry``: a file name to its path in the geometry library.
    fs_build : str, optional
        The row's FS_BUILD.

    Raises
    ------
    GeometryRowError
        An unknown route, a malformed override, or a route on an IGES that no route reaches.
    """
    name = _stated(variables, GEOMETRY_VARIABLE)
    lowered = name.lower()
    if lowered.endswith(GEOMETRY_ROW_SUFFIX):
        return _configuration_request(variables, pol, resolve(name), fs_build)
    if lowered.endswith(_IGES_SUFFIXES) and _stated(variables, MESH_ROUTE_VARIABLE):
        route = _route_of(variables, pol, default=None)
        return GeometryRowRequest(
            pol,
            resolve(name),
            "iges",
            route,
            controls=_controls(variables, resolve),
            fs_build=fs_build,
        )
    if name:
        _skip_keys_of_a_mesh_file(variables, pol, name)
    return None


def _controls(variables: Mapping[str, str], resolve: Callable[[str], Path]) -> Path | None:
    stated = _stated(variables, MESH_CONTROLS_VARIABLE)
    return resolve(stated) if stated else None


def _configuration_request(
    variables: Mapping[str, str], pol: str, source: Path, fs_build: str | None
) -> GeometryRowRequest:
    stated = _stated(variables, MESH_ROUTE_VARIABLE)
    if not stated:
        warn(
            f"matrix row POL {pol}: {source.name} states no {MESH_ROUTE_VARIABLE}; the row is "
            "read as native. Write native, full_grid or quad_dominant to say which.",
            PyflightstreamWarning,
            stacklevel=2,
        )
    params = _stated(variables, GEOM_PARAMS_VARIABLE)
    controls = _stated(variables, MESH_CONTROLS_VARIABLE)
    return GeometryRowRequest(
        pol,
        source,
        "configuration",
        _route_of(variables, pol, default="native"),
        configuration=_stated(variables, GEOM_CONFIGURATION_VARIABLE) or None,
        variant=_stated(variables, GEOM_VARIANT_VARIABLE) or "clean",
        overrides=_parse_params(params, pol) if params else {},
        controls=source.with_name(controls) if controls else None,
        fs_build=fs_build,
    )


def _configurations_of(source: Path) -> list[str]:
    """Return the configuration names of a file, empty when it declares none."""
    from pyflightstream.workspace._geom_run import list_configurations

    return sorted(list_configurations(source).get("configurations", {}))


def _short(digest: str) -> str:
    """Return the 16-hex form of a digest, the form used in folder names."""
    return digest[:16]


def row_identity(request: GeometryRowRequest) -> tuple[str, str]:
    """Return the ``parameter_id`` the API would give these cells, and the folder's key.

    The identity is computed by the runner's own resolver, so a row cannot apply an override
    differently from the API (C2).
    """
    from pyflightstream.geometry.stages import parameter_id
    from pyflightstream.workspace._geom_run import _members, _resolve

    resolved = _resolve(request.source, request.overrides)
    _members(resolved, request.configuration, request.variant)
    parameter = parameter_id(resolved)
    key = _short(
        hashlib.sha256(
            json.dumps(
                {
                    "parameter_id": parameter,
                    "configuration": request.configuration,
                    "variant": request.variant,
                    "route": request.route,
                },
                sort_keys=True,
            ).encode("utf-8")
        ).hexdigest()
    )
    return parameter, key


def _folder_name(request: GeometryRowRequest, key: str) -> str:
    stem = request.source.name
    for suffix in (GEOMETRY_ROW_SUFFIX, *_IGES_SUFFIXES):
        if stem.lower().endswith(suffix):
            stem = stem[: -len(suffix)]
    clean = "".join(c if c.isalnum() or c in "_-" else "_" for c in stem)
    return f"gen-{clean}-{key}"


def _read_report(folder: Path) -> dict[str, Any] | None:
    try:
        data = json.loads((folder / "report.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    return data if isinstance(data, dict) else None


def _failure(request: GeometryRowRequest, report: Mapping[str, Any], folder: Path):
    where = f"stage {report.get('stage')}, check {report.get('check')}"
    detail = report.get("message") or ""
    error = GeometryRowError(
        f"matrix row POL {request.pol}: {request.source.name} was {report.get('status')} "
        f"({where}); {detail} Report: {folder / 'report.json'}."
    )
    error.report_path = folder / "report.json"
    return error


def _generate(request: GeometryRowRequest, folder: Path, generate) -> dict[str, Any]:
    """Run the generator into a sibling folder and publish it by rename."""
    if generate is None:
        from pyflightstream.workspace._geom_run import run_geometry as generate

    work = folder.with_name(f".{folder.name}.{os.getpid()}.part")
    shutil.rmtree(work, ignore_errors=True)
    try:
        report = generate(
            request.source,
            out=work,
            configuration=request.configuration,
            variant=request.variant,
            overrides=request.overrides,
            until=_UNTIL[request.route],
        )
        if folder.exists():
            shutil.rmtree(folder)  # a failed earlier generation of this identity: replaced
        work.replace(folder)
    finally:
        shutil.rmtree(work, ignore_errors=True)
    return _read_report(folder) or report


def _refuse_unnamed_configuration(request: GeometryRowRequest) -> None:
    names = _configurations_of(request.source)
    if len(names) > 1 and request.configuration is None:
        raise GeometryRowError(
            f"matrix row POL {request.pol}: {request.source.name} declares several "
            f"configurations ({', '.join(names)}); name one in {GEOM_CONFIGURATION_VARIABLE}."
        )


def _instruction_text(name: str, build: str | None, table: tuple[str, str, str], boundaries):
    """Return the text of an instruction: ``table`` is the source table, its file and its units."""
    kind, source, units = table
    lines = [f'name = "{name}"']
    if build:
        lines.append(f'fs_build = "{build}"')
    names = ", ".join(json.dumps(item) for item in boundaries)
    lines += ['outputs = ["fsm"]', f"boundaries = [{names}]", "", f"[{kind}]"]
    lines += [f'file = "{source}"', f'units = "{units}"']
    if kind == "cad":
        # The importer's one boundary is named with a space, which a boundary name cannot carry:
        # the instruction renames it to the one word it states (the first boundary).
        lines += ["", "[[operations]]", 'op = "rename"']
        lines += [f'surface = "{NATIVE_BOUNDARY}"', f"to = {json.dumps(boundaries[0])}"]
    return "\n".join(lines) + "\n"


def _write_instruction(folder: Path, name: str, request, table, boundaries) -> Path:
    """Write and re-read the instruction of a row; ``table`` is (kind, file, units)."""
    from pyflightstream.workspace._geometry_instruction import read_geometry_instruction

    path = folder / f"{name}.geometry.toml"
    path.write_text(
        _instruction_text(name, request.fs_build, table, boundaries),
        encoding="utf-8",
    )
    read_geometry_instruction(path)
    return path


def _native(request: GeometryRowRequest, folder: Path, name: str, report) -> None:
    """Write the native route's instruction: the solver's CAD importer builds the IGES."""
    outputs = report.get("outputs", {})
    iges = Path(str(outputs.get("iges", ""))).name
    if not iges or not (folder / iges).is_file():
        raise GeometryRowError(
            f"matrix row POL {request.pol}: the generation wrote no IGES, so the native route "
            "has nothing to build."
        )
    _write_instruction(
        folder, name, request, ("cad", iges, "FILE"), [request.source.name.split(".")[0]]
    )


def mesh_with_strategy_1(
    request: GeometryRowRequest, folder: Path, name: str, report, mesh_configuration=None
) -> None:
    """Mesh the configuration by strategy 1 of PFS-2214 for the quad_dominant route."""
    if mesh_configuration is None:
        from pyflightstream.workspace import _geometry_mesh

        mesh_configuration = getattr(_geometry_mesh, "mesh_configuration", None)
    if mesh_configuration is None:
        raise GeometryRowError(
            f"matrix row POL {request.pol}: MESH_ROUTE quad_dominant needs strategy 1 of "
            "PFS-2214, which this tree does not carry."
        )
    _mesh_with(request, folder, name, mesh_configuration)


def mesh_with_strategy_2(
    request: GeometryRowRequest, folder: Path, name: str, report, mesh_full_grid=None
) -> None:
    """Mesh the configuration by strategy 2 of PFS-2214 (full grid) for the full_grid route."""
    if mesh_full_grid is None:
        from pyflightstream.workspace import _geometry_mesh_s2

        mesh_full_grid = _geometry_mesh_s2.mesh_full_grid
    _mesh_with(request, folder, name, mesh_full_grid)


def _mesh_with(request: GeometryRowRequest, folder: Path, name: str, mesher) -> None:
    """Mesh a generated row with its controls file and write the ``[mesh]`` instruction."""
    controls = request.controls or request.source.with_name(
        request.source.name[: -len(GEOMETRY_ROW_SUFFIX)] + ".mesh.toml"
    )
    if not controls.is_file():
        raise GeometryRowError(
            f"matrix row POL {request.pol}: the mesh controls {controls.name} are not in the "
            f"geometry library; write them or name another in {MESH_CONTROLS_VARIABLE}."
        )
    from pyflightstream.workspace._geom_run import _resolve

    resolved = _resolve(request.source, request.overrides)
    result = mesher(resolved, controls, out=folder, descriptor=name)
    members = list(result.record.get("members") or [name])
    written = Path(result.written.get("obj", folder / f"{name}.obj"))
    _write_instruction(folder, name, request, ("mesh", written.name, "METER"), members)


#: The meshers of the routes that mesh: strategy 1 of PFS-2214 for ``quad_dominant`` and
#: strategy 2 for ``full_grid``. An entry set to None is refused, by name, before generating.
MESH_STRATEGIES: dict[str, Callable[..., None] | None] = {
    "quad_dominant": mesh_with_strategy_1,
    "full_grid": mesh_with_strategy_2,
}

#: The instruction writers, per route.
_ROUTES: dict[str, Callable[..., None]] = {"native": _native}


def _check_the_route_runs(request: GeometryRowRequest) -> None:
    """Refuse, before anything is generated, a route this tree has no code for."""
    if request.route in _ROUTES or MESH_STRATEGIES.get(request.route) is not None:
        return
    running = sorted([*_ROUTES, *(k for k, v in MESH_STRATEGIES.items() if v is not None)])
    raise GeometryRowError(
        f"matrix row POL {request.pol}: MESH_ROUTE {request.route} has no mesher on this tree "
        f"(strategy 2 of PFS-2214 meshes full_grid); the routes that run are "
        f"{', '.join(running)}."
    )


def _write_route(request: GeometryRowRequest, folder: Path, name: str, report) -> None:
    mesher = _ROUTES.get(request.route) or MESH_STRATEGIES[request.route]
    if mesher is not None:
        mesher(request, folder, name, report)


def prepare_row_geometry(
    request: GeometryRowRequest, geometries: Path, *, generate=None
) -> RowGeometry:
    """Generate the geometry of one row, or reuse the equal generation, and write its instruction.

    Parameters
    ----------
    request : GeometryRowRequest
        The row's cells, read by :func:`plan_row_geometry`.
    geometries : Path
        The ``inputs/geometries`` folder of the workspace; the result is a folder of it.
    generate : callable, optional
        The runner, with the signature of ``run_geometry``; that function by default.

    Returns
    -------
    RowGeometry
        The folder, the instruction's name, the ``.fsm`` the row opens and the report.

    Raises
    ------
    GeometryRowError
        The input is refused, or the generation failed a check: the row alone is lost.
    """
    if request.kind == "iges":
        return _from_iges(request, geometries)
    _check_the_route_runs(request)
    _refuse_unnamed_configuration(request)
    try:
        _, key = row_identity(request)
    except (PyflightstreamError, ValueError, OSError, tomllib.TOMLDecodeError) as error:
        raise GeometryRowError(f"matrix row POL {request.pol}: {error}") from error
    name = _folder_name(request, key)
    folder = geometries / name
    report = _read_report(folder) if (folder / f"{name}.geometry.toml").is_file() else None
    reused = bool(report and report.get("status") in _REUSABLE)
    if not reused:
        report = _generate(request, folder, generate)
    if report is None or report.get("status") not in _REUSABLE:
        raise _failure(request, report or {"status": "failed"}, folder)
    if not reused:
        _write_route(request, folder, name, report)
    return RowGeometry(folder, name, folder / f"{name}.fsm", report, reused)


def _from_iges(request: GeometryRowRequest, geometries: Path) -> RowGeometry:
    """Prepare a row that names an IGES: native builds it through ``[cad]``, no mesh route yet."""
    if request.route != "native":
        raise GeometryRowError(
            f"matrix row POL {request.pol}: MESH_ROUTE {request.route} meshes an IGES file "
            "directly, which this tree does not carry; the route that runs on an IGES is native."
        )
    name = _folder_name(request, _short(hashlib.sha256(request.source.read_bytes()).hexdigest()))
    folder = geometries / name
    if not (folder / f"{name}.geometry.toml").is_file():
        work = folder.with_name(f".{name}.{os.getpid()}.part")
        shutil.rmtree(work, ignore_errors=True)
        work.mkdir(parents=True)
        shutil.copy2(request.source, work / request.source.name)
        work.replace(folder)
        table = ("cad", request.source.name, "FILE")
        _write_instruction(folder, name, request, table, [request.source.stem.split(".")[0]])
    return RowGeometry(folder, name, folder / f"{name}.fsm", {"status": "accepted"}, False)


def failure_record(error: GeometryRowError) -> dict[str, str]:
    """Return the entry of ``ResolvedMatrix.geometry_failures`` for one failed row."""
    return {"message": str(error), "report": str(error.report_path or "")}


def _row_geometry_path(
    inputs_dir: Path,
    variables: Mapping[str, str],
    pol: str,
    resolve: Callable[[str], Path],
    fs_build: str | None,
    *,
    generate: Callable[..., dict[str, Any]] | None = None,
) -> Path | None:
    """Generate the geometry a row states by configuration or route; None when it states none.

    The row names a ``.geom.toml``, or an IGES with a MESH_ROUTE: the same runner the API calls
    makes it, and the row opens the ``.fsm`` that the geometry stage builds from the instruction
    written beside it. A row with no such cell is bound as it always was.

    Raises
    ------
    GeometryRowError
        The row's geometry cannot be produced, or the solver has not built it yet.
    """
    request = plan_row_geometry(variables, pol, resolve, fs_build=fs_build)
    if request is None:
        return None
    built = prepare_row_geometry(request, inputs_dir / "geometries", generate=generate)
    if not built.geometry.is_file():
        raise GeometryRowError(
            f"matrix row POL {pol}: the geometry is generated ({built.folder}) and the solver "
            f"has not built it; run pyfs-workspace geometry build {built.name} --apply --build "
            f"{fs_build or '<build>'} and run the matrix again."
        )
    return built.geometry


def record_geometry_failures(
    failures: Mapping[str, Mapping[str, str]],
    workspace: Any,
    campaign: Any,
    default: str | None,
) -> None:
    """Record each row whose generated geometry failed, as GEOMETRY_FAILED, and go on.

    The row is absent from the bound campaign, so the other rows run unchanged. Each attempt is
    its own stamped record, because the manifest refuses a repeated identity and a second run
    of the row is a second fact.
    """
    from pyflightstream.workspace._geom_run import _package_version
    from pyflightstream.workspace.manifest import MANIFEST_SCHEMA, RunRecord, RunStatus

    stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%S%f")
    for pol, failure in failures.items():
        report = failure.get("report") or "no report written"
        workspace.append_record(
            RunRecord(
                run_id=f"{campaign.name}/sim_{pol}/geometry_{stamp}",
                sim_id=pol,
                point={},
                matrix_stem=campaign.matrix_stem,
                fs_version_requested=campaign.fs_version or default or "",
                package_version=_package_version(),
                manifest_schema=MANIFEST_SCHEMA,
                script_sha256="",
                raw_flag=False,
                status=RunStatus.GEOMETRY_FAILED,
                error=f"{failure['message']} (report: {report})",
            )
        )


def generate_row_geometries(
    rows: Sequence[Any], workspace: Any, *, generate: Callable[..., dict[str, Any]] | None = None
) -> tuple[list[Any], dict[str, dict[str, str]]]:
    """Generate the geometry of every row that states one; return the rows to bind and the failures.

    A row whose ``GEOMETRY`` is a configuration, or an IGES with a route, comes back opening the
    ``.fsm`` its instruction builds; every other row comes back as it was. A row whose geometry
    cannot be produced is left out of the rows and named, with its report, among the failures,
    so one failed row never stops the others (C3).

    Parameters
    ----------
    rows : sequence of MatrixRow
        The active rows of the matrix.
    workspace : CampaignWorkspace
        Whose ``inputs/geometries`` library the rows read and the generated folders join.
    generate : callable, optional
        The runner, with the signature of ``run_geometry``; that function by default.

    Returns
    -------
    tuple of list and dict
        The rows to bind, and ``{pol: {"message": ..., "report": ...}}`` of the rows left out.

    Raises
    ------
    MatrixError
        Every row failed: there is no campaign left to bind, so the failures are the refusal.
    """
    kept: list[Any] = []
    failures: dict[str, dict[str, str]] = {}
    for row in rows:
        pol = row.pol

        def resolve(name: str, pol: str = pol) -> Path:
            try:
                return workspace.resolve_geometry(name)
            except InputArtifactError as error:
                raise InputArtifactError(
                    f"matrix row POL {pol}: the {GEOMETRY_VARIABLE} variable names geometry "
                    f"{name!r}, which the workspace input library cannot resolve. {error}"
                ) from error

        try:
            path = _row_geometry_path(
                workspace.inputs_dir,
                row.variables,
                pol,
                resolve,
                row.fs_build.strip() or None,
                generate=generate,
            )
        except GeometryRowError as error:
            failures[pol] = failure_record(error)
            continue
        if path is None:
            kept.append(row)
        else:
            kept.append(replace(row, variables={**row.variables, GEOMETRY_VARIABLE: path.name}))
    if rows and not kept:
        raise MatrixError(
            "no row of the matrix has a geometry to open: "
            + " ".join(failure["message"] for failure in failures.values())
        )
    return kept, failures
